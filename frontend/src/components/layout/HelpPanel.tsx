// ═══════════════════════════════════════════════════════════
// HelpSection — بخش کشویی
// ═══════════════════════════════════════════════════════════

function HelpSection({
  section,
  defaultOpen = false,
}: {
  section: {
    icon: React.ReactNode;
    title: string;
    content: string[];
    indicatorGroups?: Array<{
      name: string;
      icon: string;
      indicators: string[];
    }>;
  };
  defaultOpen?: boolean;
}) {
  const [open, setOpen] = useState(defaultOpen);

  return (
    <div className="rounded-lg border border-white/5 bg-[#051118] overflow-hidden">
      <button
        type="button"
        onClick={() => setOpen((value) => !value)}
        className="flex w-full items-center justify-between gap-2 p-3 text-right transition-colors hover:bg-[#d6ad60]/5"
        aria-expanded={open}
      >
        <div className="flex items-center gap-2 min-w-0 flex-1">
          {section.icon}
          <h3 className="text-xs font-bold truncate text-gray-200">
            {section.title}
          </h3>
        </div>

        <ChevronDown
          className={`h-4 w-4 shrink-0 transition-transform ${
            open ? "rotate-180 text-[#d6ad60]" : "text-gray-500"
          }`}
        />
      </button>

      {open && (
        <div className="px-3 pb-3 space-y-2.5 border-t border-white/5 pt-2">
          {section.indicatorGroups?.map((group) => (
            <div key={group.name} className="space-y-1.5">
              <div className="flex items-center gap-1.5">
                <span className="text-[11px]">{group.icon}</span>
                <span className="text-[10.5px] font-bold text-gray-200">
                  {group.name}
                </span>
                <span className="num text-[8.5px] text-gray-500">
                  ({group.indicators.length})
                </span>
              </div>

              <div className="flex flex-wrap gap-1">
                {group.indicators.map((ind) => (
                  <span
                    key={ind}
                    className="inline-flex items-center rounded-md border border-[#d6ad60]/20 bg-[#d6ad60]/5 px-1.5 py-0.5 text-[9px] font-medium text-[#d6ad60]/90"
                  >
                    {ind}
                  </span>
                ))}
              </div>
            </div>
          ))}

          {section.content.length > 0 && (
            <ul className="space-y-1 pt-1 text-[10.5px] text-gray-400 list-disc pr-4">
              {section.content.map((item, i) => (
                <li key={i} className="leading-relaxed">
                  {item}
                </li>
              ))}
            </ul>
          )}
        </div>
      )}
    </div>
  );
}

